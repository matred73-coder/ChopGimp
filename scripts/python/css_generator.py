# Map GIMP blend modes to CSS mix-blend-mode values
BLEND_MODE_MAP = {
    Gimp.LayerMode.NORMAL: "normal",
    Gimp.LayerMode.MULTIPLY: "multiply",
    Gimp.LayerMode.SCREEN: "screen",
    Gimp.LayerMode.OVERLAY: "overlay",
    Gimp.LayerMode.DARKEN_ONLY: "darken",
    Gimp.LayerMode.LIGHTEN_ONLY: "lighten",
    Gimp.LayerMode.DODGE: "color-dodge",
    Gimp.LayerMode.BURN: "color-burn",
    Gimp.LayerMode.HARDLIGHT: "hard-light",
    Gimp.LayerMode.SOFTLIGHT: "soft-light",
    Gimp.LayerMode.DIFFERENCE: "difference",
    Gimp.LayerMode.ADDITION: "normal",
    Gimp.LayerMode.EXCLUSION: "exclusion",
    Gimp.LayerMode.HSL_COLOR: "color",
    Gimp.LayerMode.LCH_HUE: "hue",
    Gimp.LayerMode.LCH_LIGHTNESS: "luminosity",
    Gimp.LayerMode.HSV_SATURATION: "saturation",
}


def sanitize_class_name(name):
    """Convert layer name to a valid CSS class name."""
    result = ""
    for ch in name.lower():
        if ch.isalnum() or ch in ('-', '_'):
            result += ch
        elif ch == ' ':
            result += '-'
    return result or "layer"


def rgb_to_hex(r, g, b):
    """Convert float 0-1 RGB to hex color string."""
    return "#{:02x}{:02x}{:02x}".format(
        int(r * 255), int(g * 255), int(b * 255))


def analyze_layer(image, layer, pdb):
    """Extract CSS-relevant properties from a layer."""
    props = {}

    name = layer.get_name()
    props["name"] = name
    props["class"] = sanitize_class_name(name)

    # Position (offset from top-left of canvas)
    off = layer.get_offsets()
    props["left"] = off.offset_x
    props["top"] = off.offset_y

    # Size
    props["width"] = layer.get_width()
    props["height"] = layer.get_height()

    # Opacity
    props["opacity"] = round(layer.get_opacity() / 100.0, 2)

    # Blend mode
    mode = layer.get_mode()
    props["blend_mode"] = BLEND_MODE_MAP.get(mode, "normal")

    # Check if it's a text layer
    is_text = False
    try:
        is_text = layer.is_text_layer()
    except Exception:
        pass

    if is_text:
        props["is_text"] = True
        try:
            # Extract text properties
            font = pdb.run_procedure("gimp-text-layer-get-font",
                                     [layer]).index(1)
            props["font_family"] = font
        except Exception:
            props["font_family"] = "sans-serif"

        try:
            size = pdb.run_procedure("gimp-text-layer-get-font-size",
                                     [layer]).index(1)
            props["font_size"] = size
        except Exception:
            pass

        try:
            color_result = pdb.run_procedure("gimp-text-layer-get-color",
                                              [layer])
            color = color_result.index(1)
            props["color"] = rgb_to_hex(color.r, color.g, color.b)
        except Exception:
            pass

        try:
            text = pdb.run_procedure("gimp-text-layer-get-text",
                                     [layer]).index(1)
            props["text_content"] = text
        except Exception:
            pass
    else:
        props["is_text"] = False

    # Check if layer name suggests shadow
    lower_name = name.lower()
    if "shadow" in lower_name:
        props["is_shadow"] = True
    else:
        props["is_shadow"] = False

    return props


def generate_css(image, visible_only=True):
    """Iterate all layers and generate CSS."""
    pdb = Gimp.get_pdb()
    css_lines = []
    css_lines.append("/* Generated by PhotoGIMP Pro — Generateur CSS */")
    css_lines.append(f"/* Canevas: {image.get_width()}px x {image.get_height()}px */")
    css_lines.append("")

    # Container
    css_lines.append(".canvas {")
    css_lines.append(f"  position: relative;")
    css_lines.append(f"  width: {image.get_width()}px;")
    css_lines.append(f"  height: {image.get_height()}px;")
    css_lines.append(f"  overflow: hidden;")
    css_lines.append("}")
    css_lines.append("")

    layers = image.get_layers()
    # Reverse so bottom layers come first in CSS (natural stacking)
    for layer in reversed(layers):
        if visible_only and not layer.get_visible():
            continue
        if layer.is_group():
            # Recurse into group
            for child in reversed(layer.get_children()):
                if visible_only and not child.get_visible():
                    continue
                props = analyze_layer(image, child, pdb)
                css_lines.extend(format_layer_css(props))
        else:
            props = analyze_layer(image, layer, pdb)
            css_lines.extend(format_layer_css(props))

    return "\n".join(css_lines)


def format_layer_css(props):
    """Format a single layer's properties as CSS."""
    lines = []
    cls = props["class"]
    lines.append(f".{cls} {{")
    lines.append(f"  /* Layer: {props['name']} */")
    lines.append(f"  position: absolute;")
    lines.append(f"  left: {props['left']}px;")
    lines.append(f"  top: {props['top']}px;")
    lines.append(f"  width: {props['width']}px;")
    lines.append(f"  height: {props['height']}px;")

    if props["opacity"] < 1.0:
        lines.append(f"  opacity: {props['opacity']};")

    if props["blend_mode"] != "normal":
        lines.append(f"  mix-blend-mode: {props['blend_mode']};")

    if props["is_text"]:
        if "font_family" in props:
            lines.append(f"  font-family: '{props['font_family']}', sans-serif;")
        if "font_size" in props:
            lines.append(f"  font-size: {props['font_size']}px;")
        if "color" in props:
            lines.append(f"  color: {props['color']};")

    if props.get("is_shadow"):
        # Approximate a box-shadow from layer offset relative to canvas center
        lines.append(f"  /* Detected as shadow layer */")
        lines.append(f"  box-shadow: {props['left']}px {props['top']}px 10px rgba(0, 0, 0, {props['opacity']});")

    lines.append("}")
    lines.append("")
    return lines


def run_css_generator(procedure, run_mode, image, drawables, config, data):
    """Main plugin: analyze layers and output CSS."""
    if run_mode == Gimp.RunMode.INTERACTIVE:
        GimpUi.init("python-fu-css-generator")

        # Generate CSS first
        css_output = generate_css(image, visible_only=True)

        dialog = Gtk.Dialog(title="Generate CSS", flags=0)
        dialog.set_default_size(600, 500)
        dialog.add_button("_Close", Gtk.ResponseType.CLOSE)
        dialog.add_button("Copy to _Clipboard", 1)
        dialog.add_button("_Save to File...", 2)

        content = dialog.get_content_area()
        content.set_spacing(8)
        content.set_border_width(12)

        # Options
        hbox = Gtk.Box(orientation=Gtk.Orientation.HORIZONTAL, spacing=6)
        chk_visible = Gtk.CheckButton(label="Visible layers only")
        chk_visible.set_active(True)
        hbox.pack_start(chk_visible, False, False, 0)

        refresh_btn = Gtk.Button(label="Refresh")
        hbox.pack_end(refresh_btn, False, False, 0)
        content.pack_start(hbox, False, False, 0)

        # CSS output text view
        scroll = Gtk.ScrolledWindow()
        scroll.set_policy(Gtk.PolicyType.AUTOMATIC, Gtk.PolicyType.AUTOMATIC)
        scroll.set_vexpand(True)

        text_view = Gtk.TextView()
        text_view.set_monospace(True)
        text_view.set_editable(False)
        text_buf = text_view.get_buffer()
        text_buf.set_text(css_output)
        scroll.add(text_view)
        content.pack_start(scroll, True, True, 0)

        # Status
        status_label = Gtk.Label(label="CSS generated from image layers.")
        status_label.set_xalign(0)
        content.pack_start(status_label, False, False, 0)

        def do_refresh(_widget=None):
            vis = chk_visible.get_active()
            new_css = generate_css(image, visible_only=vis)
            text_buf.set_text(new_css)
            status_label.set_text("CSS refreshed.")

        refresh_btn.connect("clicked", do_refresh)

        dialog.show_all()

        while True:
            response = dialog.run()

            if response == 1:
                # Copy to clipboard
                start = text_buf.get_start_iter()
                end = text_buf.get_end_iter()
                css_text = text_buf.get_text(start, end, False)
                clipboard = Gtk.Clipboard.get_default(
                    dialog.get_display())
                clipboard.set_text(css_text, -1)
                clipboard.store()
                status_label.set_text("CSS copied to clipboard.")

            elif response == 2:
                # Save to file
                save_dialog = Gtk.FileChooserDialog(
                    title="Save CSS File",
                    parent=dialog,
                    action=Gtk.FileChooserAction.SAVE)
                save_dialog.add_button("_Cancel", Gtk.ResponseType.CANCEL)
                save_dialog.add_button("_Save", Gtk.ResponseType.OK)
                save_dialog.set_do_overwrite_confirmation(True)
                save_dialog.set_current_name("layers.css")

                css_filter = Gtk.FileFilter()
                css_filter.set_name("CSS files")
                css_filter.add_pattern("*.css")
                save_dialog.add_filter(css_filter)

                if save_dialog.run() == Gtk.ResponseType.OK:
                    filepath = save_dialog.get_filename()
                    start = text_buf.get_start_iter()
                    end = text_buf.get_end_iter()
                    css_text = text_buf.get_text(start, end, False)
                    try:
                        with open(filepath, "w", encoding="utf-8") as f:
                            f.write(css_text)
                        status_label.set_text(f"Saved to {filepath}")
                    except Exception as e:
                        status_label.set_text(f"Error: {e}")
                save_dialog.destroy()

            else:
                break

        dialog.destroy()

    return procedure.new_return_values(Gimp.PDBStatusType.SUCCESS, GLib.Error())


class CssGenerator(Gimp.PlugIn):

    def do_set_i18n(self, procname):
        return False

    def do_query_procedures(self):
        return ['python-fu-css-generator']

    def do_create_procedure(self, name):
        if name == 'python-fu-css-generator':
            procedure = Gimp.ImageProcedure.new(
                self, name, Gimp.PDBProcType.PLUGIN, run_css_generator, None)
            procedure.set_image_types("*")
            procedure.set_sensitivity_mask(
                Gimp.ProcedureSensitivityMask.DRAWABLE |
                Gimp.ProcedureSensitivityMask.DRAWABLES)
            procedure.set_documentation(
                _("Generer CSS..."),
                _("Analyser les calques de l'image et generer les proprietes CSS de positionnement, couleurs et texte."),
                name)
            procedure.set_menu_label(_("Generer _CSS..."))
            procedure.set_attribution("PhotoGIMP Pro", "GPL v3+", "2026")
            procedure.add_menu_path("<Image>/Filters/Design")
            return procedure

        return None


Gimp.main(CssGenerator.__gtype__, sys.argv)
